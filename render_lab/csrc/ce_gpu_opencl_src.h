/*
 * Qascade CE — OpenCL 内核源码（内嵌字符串, ce_gpu_opencl.c 唯一包含点）。
 *
 * OpenCL C 1.2 无 static inline 函数, 无法直接含 ce_gpu_kernels.h;
 * 本文件与 ce_gpu_kernels.h 逐行同构（变更需同步）: 同一份算术,
 * #pragma OPENCL FP_CONTRACT OFF 禁 fma 收缩 = 位级等价硬前提。
 */
static const char* CE_GPU_CL_MIX_SRC =
    "#pragma OPENCL FP_CONTRACT OFF\n"
    "#pragma OPENCL EXTENSION cl_khr_fp64 : enable\n"
    "__kernel void ce_gpu_cl_mix_batch(\n"
    "    __global const float* vals, __global const uchar* acts,\n"
    "    __global const float* anchors, __global const int* nlays,\n"
    "    int n_univ, int lmax, float mod_gain,\n"
    "    __global uchar* out, __global uchar* act_any)\n"
    "{\n"
    "    int g = get_global_id(0);\n"
    "    if (g >= n_univ * 512) return;\n"
    "    int u = g / 512;\n"
    "    int c = g - u * 512;\n"
    "    ulong base = (ulong)u * lmax * 512;\n"
    "    int pidx = -1;\n"
    "    int any_a = 0;\n"
    "    float best_abs = -1.0f;\n"
    "    float sum_delta = 0.0f;\n"
    "    float primary_delta;\n"
    "    float res;\n"
    "    float sum_active = 0.0f;\n"
    "    float cnt_active = 0.0f;\n"
    "    int nlay = nlays[u];\n"
    "    for (int l = 0; l < nlay; l++) {\n"
    "        float v = vals[base + (ulong)l * 512 + c];\n"
    "        float d;\n"
    "        if (acts[base + (ulong)l * 512 + c]) {\n"
    "            any_a = 1;\n"
    "            d = v - anchors[base + (ulong)l * 512 + c];\n"
    "            sum_active += v;\n"
    "            cnt_active += 1.0f;\n"
    "        } else {\n"
    "            d = 0.0f;\n"
    "        }\n"
    "        sum_delta += d;\n"
    "        if (fabs(d) > best_abs) {\n"
    "            best_abs = fabs(d);\n"
    "            pidx = l;\n"
    "        }\n"
    "    }\n"
    "    act_any[(ulong)u * 512 + c] = (uchar)any_a;\n"
    "    if (pidx >= 0 && acts[base + (ulong)pidx * 512 + c]) {\n"
    "        primary_delta = vals[base + (ulong)pidx * 512 + c]\n"
    "                      - anchors[base + (ulong)pidx * 512 + c];\n"
    "        res = vals[base + (ulong)pidx * 512 + c]\n"
    "            + (sum_delta - primary_delta) * mod_gain;\n"
    "    } else if (any_a) {\n"
    "        res = (cnt_active > 0.0f) ? (sum_active / cnt_active) : 0.0f;\n"
    "    } else {\n"
    "        res = 0.0f;\n"
    "    }\n"
    "    if (res < 0.0f) res = 0.0f;\n"
    "    else if (res > 255.0f) res = 255.0f;\n"
    "    if (res != res) res = 0.0f;\n"
    "    out[(ulong)u * 512 + c] = (uchar)res;\n"
    "}\n";

static const char* CE_GPU_CL_WAVE_SRC =
    "#pragma OPENCL FP_CONTRACT OFF\n"
    "#pragma OPENCL EXTENSION cl_khr_fp64 : enable\n"
    "double ce_gpu_cl_mod1(double x)\n"
    "{\n"
    "    double m = fmod(x, 1.0);\n"
    "    if (m < 0.0) m += 1.0;\n"
    "    return m;\n"
    "}\n"
    "double ce_gpu_cl_wave(double x, int idx)\n"
    "{\n"
    "    switch (idx) {\n"
    "    case 0: return (sin(x * 2.0 * 3.14159265358979323846) + 1.0) / 2.0;\n"
    "    case 1: return (ce_gpu_cl_mod1(x) < 0.5) ? 1.0 : 0.0;\n"
    "    case 2: return ce_gpu_cl_mod1(x);\n"
    "    case 3: return 1.0 - fabs(2.0 * ce_gpu_cl_mod1(x) - 1.0);\n"
    "    case 4: {\n"
    "        /* 负数转型经 (long) 中转: MSVC 两补码回绕, GPU 直转分歧(实测) */\n"
    "        ulong k = (ulong)(long)rint(x * 100000.0);\n"
    "        k = (k ^ (k >> 30)) * 0xBF58476D1CE4E5B9UL;\n"
    "        k = (k ^ (k >> 27)) * 0x94D049BB133111EBUL;\n"
    "        k = (k ^ (k >> 31));\n"
    "        return (double)(k & 0xFFFFFFFFUL) / 4294967296.0;\n"
    "    }\n"
    "    case 5: return (cos(x * 2.0 * 3.14159265358979323846) + 1.0) / 2.0;\n"
    "    case 6: return fabs(sin(x * 3.14159265358979323846));\n"
    "    case 7: return (exp(ce_gpu_cl_mod1(x)) - 1.0) / "
    "(2.7182818284590452354 - 1.0);\n"
    "    default: return (sin(x * 2.0 * 3.14159265358979323846) + 1.0) / 2.0;\n"
    "    }\n"
    "}\n"
    "__kernel void ce_gpu_cl_wave_batch(\n"
    "    __global const double* t, __global const double* speed,\n"
    "    __global const double* phase_step, __global const double* lo,\n"
    "    __global const double* hi, __global const int* wave_fn,\n"
    "    __global const int* offsets,\n"
    "    int ntask, __global uchar* out)\n"
    "{\n"
    "    int total = offsets[ntask];\n"
    "    int g = get_global_id(0);\n"
    "    if (g >= total) return;\n"
    "    int lo_t = 0;\n"
    "    int hi_t = ntask - 1;\n"
    "    while (lo_t < hi_t) {\n"
    "        int mid = (lo_t + hi_t) >> 1;\n"
    "        if (offsets[mid + 1] <= g) lo_t = mid + 1;\n"
    "        else hi_t = mid;\n"
    "    }\n"
    "    int task = lo_t;\n"
    "    double phase = (double)(g - offsets[task]) * phase_step[task];\n"
    "    double v = ce_gpu_cl_wave(t[task] * speed[task] + phase, "
    "wave_fn[task]);\n"
    "    double val = lo[task] + v * (hi[task] - lo[task]);\n"
    "    int iv = (int)val;\n"
    "    if (iv < 0) iv = 0;\n"
    "    else if (iv > 255) iv = 255;\n"
    "    out[g] = (uchar)iv;\n"
    "}\n";
