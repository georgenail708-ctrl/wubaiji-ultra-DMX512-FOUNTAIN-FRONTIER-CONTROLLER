def display_category(value):
    from .effect_engine import normalize_effect_category
    original = normalize_effect_category(value)
    return DISPLAY_CATEGORIES.get(original, original)


def category_for(preset):
    return display_category(getattr(preset, "category", ""))


def catalog_filter(sub):
    return category_for, display_category(sub) if sub else ""


def display_name(preset):
    return NAMES.get(getattr(preset, "id", ""), getattr(preset, "name", ""))


def display_description(preset):
    return DESCRIPTIONS.get(getattr(preset, "id", ""), getattr(preset, "description", ""))


def can_restore_preset(panel, preset_id):
    """Stored registered IDs remain editable; the new catalog stays curated."""
    if panel._is_preset_visible(preset_id):
        return True
    from .effect_engine import get_engine
    return preset_id in get_engine()._retired_presets
